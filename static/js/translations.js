// Global function to change language and translate page completely
function changeLanguage(langCode) {
    if (!TRANSLATIONS[langCode]) langCode = 'en';
    localStorage.setItem('svit_lang', langCode);

    const langDict = TRANSLATIONS[langCode];
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (langDict[key]) {
            if (key === 'accreditation') {
                elem.innerHTML = langDict[key];
            } else {
                elem.textContent = langDict[key];
            }
        }
    });

    // Update placeholder text for inputs
    document.querySelectorAll('[data-i18n-placeholder]').forEach(elem => {
        const key = elem.getAttribute('data-i18n-placeholder');
        if (langDict[key]) {
            elem.placeholder = langDict[key];
        }
    });

    // Update dropdown selector UI if present
    const langSelect = document.getElementById('language-selector-dropdown');
    if (langSelect) {
        langSelect.value = langCode;
    }

    // Call admin JS data refresh if active on admin page
    if (window.refreshAdminData) {
        window.refreshAdminData(langCode);
    }
}

// Auto-initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('svit_lang') || 'en';
    changeLanguage(savedLang);
});
